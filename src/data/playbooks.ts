import type { Playbook } from '../types'

type PlaybookSeed = Omit<Playbook, 'lastVerified' | 'steps'>

const TODAY = '2026-07-31'

const STEP_TEMPLATES: Record<Playbook['method'], string[]> = {
  direct_edit: [
    'Open account settings or profile page.',
    'Change email address inside account details.',
    'Verify new address from inbox.',
    'Test login and recovery paths.',
    'Keep old address until new one works end to end.',
  ],
  add_verify_promote_remove: [
    'Add new email or alias.',
    'Verify new address.',
    'Make new address primary.',
    'Review recovery and notification settings.',
    'Remove old address after fresh login succeeds.',
  ],
  trusted_device: [
    'Open security settings on trusted device or active session.',
    'Add or choose new address.',
    'Verify new address.',
    'Confirm linked services still work.',
    'Review whether old address should remain linked.',
  ],
  support_assisted: [
    'Open official support or help page.',
    'Request email change with required verification.',
    'Confirm new address and recovery methods.',
    'Test login after support updates account.',
    'Keep old address until change is complete.',
  ],
  recreate: [
    'Export anything the service lets you save first.',
    'Create new account with new email.',
    'Move subscriptions, purchases, or connections.',
    'Update recovery information everywhere else.',
    'Close old account only after replacement is working.',
  ],
  unknown: [
    'Open official account or support page.',
    'Find current email-change process.',
    'Follow required verification steps.',
    'Test login after update.',
    'Keep old address until you confirm new flow works.',
  ],
}

function makePlaybook(seed: PlaybookSeed): Playbook {
  return {
    ...seed,
    lastVerified: TODAY,
    steps: STEP_TEMPLATES[seed.method],
  }
}

