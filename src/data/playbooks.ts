const playbookDomains = PLAYBOOKS.flatMap((playbook) =>
  playbook.domains.map((domain) => ({ domain, playbook })),
).sort((left, right) => right.domain.length - left.domain.length)

export function findPlaybook(domain: string): Playbook | undefined {
  const normalized = domain.toLowerCase().replace(/^www\./, '')
  return playbookDomains.find(
    (candidate) =>
      normalized === candidate.domain ||
      normalized.endsWith(`.${candidate.domain}`),
  )?.playbook
}
